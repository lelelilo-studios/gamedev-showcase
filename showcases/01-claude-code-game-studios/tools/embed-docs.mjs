#!/usr/bin/env node
// Embeds the studio's paperwork into binder-docs.js so the page can show it without a server.
// The .md files in studio/ stay the source; run this after any of them changes:
//   node tools/embed-docs.mjs            (from this folder)
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = {}, files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name), st = statSync(p);
    if (st.isDirectory()) walk(p);
    else {
      const rel = relative(here, p).split('\\').join('/');
      files.push({ path: rel, bytes: st.size });
      if (/\.(md|yaml|txt|json|py)$/.test(name)) docs[rel] = readFileSync(p, 'utf8');
    }
  }
})(join(here, 'studio'));
const out = '/* Generated by tools/embed-docs.mjs from the files in studio/. Do not edit by hand. */\n' +
  'window.BINDER_DOCS = ' + JSON.stringify(docs) + ';\n' +
  'window.BINDER_FILES = ' + JSON.stringify(files) + ';\n';
writeFileSync(join(here, 'binder-docs.js'), out);
console.log(`binder-docs.js: ${Object.keys(docs).length} documents, ${files.length} files, ${(out.length / 1024).toFixed(1)} KB`);
